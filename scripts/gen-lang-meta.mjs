#!/usr/bin/env node
// Generates public/modules/lang-meta.mjs — the language REGISTRY.
//
// The web client no longer imports every catalogue at boot (64 files, ~5 MB):
// only English is static, the active language is fetched on demand by
// modules/i18n.mjs. The picker, the locale detection and <html dir> still
// need to know every language up front (code, native label, direction,
// flag), so that small part of each lang/<code>.mjs `meta` export is copied
// here at build time.
//
// Run after adding a language or editing a `meta` block:
//     node scripts/gen-lang-meta.mjs
// scripts/test-lang-lazy.mjs fails when the generated file is stale.
//   --check   exit 1 if the file on disk differs from a fresh generation
import fs from 'fs';
import path from 'path';
import { pathToFileURL } from 'url';

const LANG_DIR = path.resolve('public/modules/lang');
const OUT = path.resolve('public/modules/lang-meta.mjs');

// File name → catalogue code: region subtag upper-cased (pt-br → pt-BR).
export function codeOf(file) {
  const base = file.replace(/\.mjs$/, '');
  const p = base.split('-');
  return p.length > 1 ? p[0] + '-' + p.slice(1).join('-').toUpperCase() : base;
}

export async function generate() {
  const files = fs.readdirSync(LANG_DIR).filter(f => f.endsWith('.mjs')).sort();
  // English first (fallback catalogue), then alphabetical by code.
  files.sort((a, b) => (a === 'en.mjs' ? -1 : b === 'en.mjs' ? 1 : a < b ? -1 : a > b ? 1 : 0));
  const rows = [];
  for (const f of files) {
    const mod = await import(pathToFileURL(path.join(LANG_DIR, f)).href);
    const m = mod.meta || (mod.default && mod.default.meta);
    if (!m || !m.label) throw new Error(f + ': missing meta.label');
    const entry = { label: m.label, dir: m.dir || 'ltr', flag: m.flag || '' };
    rows.push('  ' + JSON.stringify(codeOf(f)) + ': ' + JSON.stringify(entry) + ',');
  }
  return [
    '// GENERATED by scripts/gen-lang-meta.mjs — do not edit by hand.',
    '// Language registry: code → { label, dir, flag }, copied from the `meta`',
    '// export of each lang/<code>.mjs. Lets modules/i18n.mjs list every language',
    '// (picker, locale detection, text direction) without loading its strings.',
    '// File name of a catalogue = its code lower-cased (pt-BR → lang/pt-br.mjs).',
    'export const LANG_META = {',
    ...rows,
    '};',
    'export const LANG_CODES = Object.keys(LANG_META);',
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const out = await generate();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== out) { console.error('lang-meta.mjs is stale — run: node scripts/gen-lang-meta.mjs'); process.exit(1); }
    console.log('lang-meta.mjs up to date');
  } else {
    fs.writeFileSync(OUT, out);
    console.log('wrote', path.relative('.', OUT), '(' + out.length + ' bytes)');
  }
}

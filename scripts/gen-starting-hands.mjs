#!/usr/bin/env node
// Computes every figure of the /starting-hands page and writes
// seo-i18n/starting-hands.json. Nothing on that page is typed from memory.
//
// For each of the 169 starting-hand types (13 pairs, 78 suited, 78 offsuit)
// it estimates the chance of winning — ties counted as a share of the pot —
// when all five board cards are dealt, against 1, 3 and 6 opponents holding
// random hands. Seeded simulation (mulberry32): the file is reproducible,
// `--check` recomputes it and compares. Evaluator: public/vendor/phe.mjs
// (checked by test-phe.mjs); scripts/test-seo-starting.mjs re-checks a few
// hands with the client's own evaluator (game/cards.mjs).
// Run: node scripts/gen-starting-hands.mjs [--check]   (~1 min)
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import * as phe from '../public/vendor/phe.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'seo-i18n', 'starting-hands.json');
export const RANKS = 'AKQJT98765432';           // chart order, strongest first
export const TRIALS = { 1: 1000000, 3: 200000, 6: 100000 };
const CODE = [];                                   // card index = suit*13 + (12 - rankIdx)
for (const s of 'shdc') for (let r = 12; r >= 0; r--) CODE.push(phe.cardCode(RANKS[r], s));
const card = (rankIdx, suit) => suit * 13 + (12 - rankIdx);

function mulberry32(a) {
  return function () { a |= 0; a = a + 0x6D2B79F5 | 0; let t = Math.imul(a ^ a >>> 15, 1 | a); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; };
}

// The 169 hand types in chart order: row i, column j. i === j pair,
// j > i suited (upper right), j < i offsuit (lower left).
export function hands() {
  const out = [];
  for (let i = 0; i < 13; i++) for (let j = 0; j < 13; j++) {
    const hi = Math.min(i, j), lo = Math.max(i, j);
    const kind = i === j ? 'pair' : (j > i ? 'suited' : 'offsuit');
    const name = RANKS[hi] + RANKS[lo] + (kind === 'suited' ? 's' : kind === 'offsuit' ? 'o' : '');
    const cards = kind === 'suited' ? [card(hi, 0), card(lo, 0)] : [card(hi, 0), card(lo, 1)];
    out.push({ name, kind, row: i, col: j, cards, combos: kind === 'pair' ? 6 : kind === 'suited' ? 4 : 12 });
  }
  return out;
}

// Equity of `hole` against `opp` random hands: win = 1, an n-way tie = 1/n.
export function equity(hole, opp, trials, seed) {
  const rnd = mulberry32(seed);
  const deck = [];
  for (let c = 0; c < 52; c++) if (c !== hole[0] && c !== hole[1]) deck.push(c);
  const H = hole.map((c) => CODE[c]), need = 5 + 2 * opp, d = deck.slice();
  let eq = 0;
  for (let t = 0; t < trials; t++) {
    for (let i = 0; i < need; i++) { const j = i + Math.floor(rnd() * (d.length - i)); const x = d[i]; d[i] = d[j]; d[j] = x; }
    const board = [CODE[d[0]], CODE[d[1]], CODE[d[2]], CODE[d[3]], CODE[d[4]]];
    const me = phe.evaluateCardCodes(H.concat(board));
    let best = Infinity, ties = 0;
    for (let o = 0; o < opp; o++) {
      const s = phe.evaluateCardCodes([CODE[d[5 + 2 * o]], CODE[d[6 + 2 * o]]].concat(board));
      if (s < best) { best = s; ties = 0; }
      if (s === best) ties++;
    }
    if (me < best) eq += 1; else if (me === best) eq += 1 / (ties + 1);
  }
  return eq / trials;
}

export function compute() {
  const list = hands().map((h, k) => {
    const r = { name: h.name, kind: h.kind, row: h.row, col: h.col, combos: h.combos };
    for (const opp of [1, 3, 6]) r['vs' + opp] = Math.round(equity(h.cards, opp, TRIALS[opp], 1000 * (k + 1) + opp) * 1e5) / 1e5;
    return r;
  });
  const order = list.slice().sort((a, b) => b.vs1 - a.vs1 || a.name.localeCompare(b.name));
  order.forEach((h, i) => { h.rank = i + 1; });
  return { note: 'Generated by scripts/gen-starting-hands.mjs — do not edit by hand.', trials: TRIALS, hands: list };
}

if (import.meta.url === 'file://' + process.argv[1]) {
  const t0 = Date.now();
  const json = JSON.stringify(compute(), null, 1) + '\n';
  if (process.argv.includes('--check')) {
    const same = readFileSync(OUT, 'utf8') === json;
    console.log(same ? 'starting-hands.json is up to date' : 'starting-hands.json is STALE — run without --check');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(OUT, json);
  console.log('written', OUT, 'in', ((Date.now() - t0) / 1000).toFixed(1) + ' s');
}

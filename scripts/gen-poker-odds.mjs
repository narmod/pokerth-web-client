#!/usr/bin/env node
// Computes every figure of the /poker-odds page and writes
// seo-i18n/odds-data.json. Nothing on that page is typed from memory: the
// head-to-head numbers are an exact enumeration of every possible board with
// the vendored evaluator (public/vendor/phe.mjs, checked by test-phe.mjs),
// the rest is plain combinatorics. scripts/test-seo-odds.mjs recomputes it.
// Run: node scripts/gen-poker-odds.mjs [--check]
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import * as phe from '../public/vendor/phe.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'seo-i18n', 'odds-data.json');

// Card notation 'As', 'Td', '7c' → phe code.
const code = (c) => phe.cardCode(c[0], c[1]);
const RANKS = '23456789TJQKA', SUITS = 'dhsc';
const DECK = [];
for (const s of SUITS) for (const r of RANKS) DECK.push(r + s);

// Head to head, every board of 5 from the 48 cards left: winA, tie, winB
// as fractions, plus the board count (always C(48,5) = 1,712,304).
export function headToHead(a, b) {
  const used = new Set([...a, ...b]);
  const rest = DECK.filter((c) => !used.has(c)).map(code);
  const A = a.map(code), B = b.map(code);
  let wa = 0, wb = 0, tie = 0, n = 0;
  const L = rest.length;
  for (let i = 0; i < L; i++) for (let j = i + 1; j < L; j++) for (let k = j + 1; k < L; k++)
    for (let l = k + 1; l < L; l++) for (let m = l + 1; m < L; m++) {
      const bd = [rest[i], rest[j], rest[k], rest[l], rest[m]];
      const sa = phe.evaluateCardCodes(A.concat(bd)), sb = phe.evaluateCardCodes(B.concat(bd));
      if (sa < sb) wa++; else if (sb < sa) wb++; else tie++;   // phe: lower = stronger
      n++;
    }
  return { winA: wa / n, tie: tie / n, winB: wb / n, boards: n };
}

// Matchups shown on the page (suits chosen so the two hands share none
// unless the hand itself is suited — the usual way these are quoted).
export const MATCHUPS = [
  { id: 'aa-kk', a: ['As', 'Ah'], b: ['Kd', 'Kc'] },
  { id: 'aa-72', a: ['As', 'Ah'], b: ['7d', '2c'] },
  { id: 'kk-ak', a: ['Ks', 'Kh'], b: ['Ad', 'Kc'] },
  { id: 'qq-ak', a: ['Qs', 'Qh'], b: ['Ad', 'Kc'] },
  { id: '22-ak', a: ['2s', '2h'], b: ['Ad', 'Kc'] },
  { id: 'ak-aq', a: ['As', 'Kh'], b: ['Ad', 'Qc'] },
  { id: 'ak-jt', a: ['As', 'Ks'], b: ['Jd', 'Td'] },
  { id: '98-ak', a: ['9s', '8s'], b: ['Ad', 'Kc'] }
];

// Outs → chance to hit: on the turn (1 card from 47), on the river from the
// turn (1 from 46), and by the river from the flop (2 from 47).
export function outsRow(outs) {
  return {
    outs,
    turn: outs / 47,
    river: outs / 46,
    flopToRiver: 1 - ((47 - outs) * (46 - outs)) / (47 * 46)
  };
}
export const DRAWS = [
  { id: 'gutshot', outs: 4 },
  { id: 'twoPairFull', outs: 4 },
  { id: 'pairTrips', outs: 5 },
  { id: 'twoOver', outs: 6 },
  { id: 'setFull', outs: 7 },
  { id: 'oesd', outs: 8 },
  { id: 'flush', outs: 9 },
  { id: 'flushGut', outs: 12 },
  { id: 'flushOesd', outs: 15 }
];

// Starting hands: how often each kind is dealt, out of C(52,2) = 1,326.
export const STARTING = [
  { id: 'specificPair', combos: 6 },        // e.g. A♠A♥ in any suits: 6 of 1,326
  { id: 'anyPair', combos: 78 },             // 13 ranks × 6
  { id: 'specificNonPair', combos: 16 },     // e.g. AK: 4 × 4
  { id: 'specificSuited', combos: 4 },       // e.g. AK suited
  { id: 'anySuited', combos: 312 },          // 78 rank pairs × 4 suits
  { id: 'twoBroadway', combos: 190 }         // two cards ten or higher: C(20,2)
];

export function compute() {
  return {
    note: 'Generated by scripts/gen-poker-odds.mjs — do not edit by hand.',
    matchups: MATCHUPS.map((m) => Object.assign({ id: m.id, handA: m.a, handB: m.b }, headToHead(m.a, m.b))),
    outs: DRAWS.map((d) => Object.assign({ id: d.id }, outsRow(d.outs))),
    starting: STARTING.map((s) => ({ id: s.id, combos: s.combos, p: s.combos / 1326 }))
  };
}

if (import.meta.url === 'file://' + process.argv[1]) {
  const t0 = Date.now();
  const data = compute();
  const json = JSON.stringify(data, null, 1) + '\n';
  if (process.argv.includes('--check')) {
    const same = readFileSync(OUT, 'utf8') === json;
    console.log(same ? 'odds-data.json is up to date' : 'odds-data.json is STALE — run without --check');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(OUT, json);
  console.log('written', OUT, 'in', ((Date.now() - t0) / 1000).toFixed(1) + ' s');
  data.matchups.forEach((m) => console.log(m.id, (m.winA * 100).toFixed(2), (m.tie * 100).toFixed(2), (m.winB * 100).toFixed(2), m.boards));
}
